"""Eternal Core 3.3.9: the ColorGrade icon pack importer (quick_settings/colorgrade_pack.py).

Every zip here is generated by the test with made-up bytes; the user's real pack is never used, committed or bundled.
"""
import base64
import importlib.util
import os
import tempfile
import unittest
import zipfile
from pathlib import Path

spec = importlib.util.spec_from_file_location("colorgrade_pack_under_test", Path(__file__).resolve().parents[1] / "quick_settings" / "colorgrade_pack.py")
pack = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pack)

PREFIX = "assets/smart_folders/colorgrade-icons-heroes-logos-9cd650/smart_folders/by_platform/"


def fake_zip(path, slugs=("psx", "ps2", "n64"), extra=()):
    with zipfile.ZipFile(path, "w") as archive:
        for slug in slugs:
            for name in pack.FILES:
                archive.writestr(PREFIX + slug + "/" + name, (slug + ":" + name).encode())
        for name, data in extra:
            archive.writestr(name, data)


class ColorGradePackTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.appdata = self.root / "AppData" / "Roaming"
        self.home = self.root / "home"
        (self.home / "Downloads").mkdir(parents=True)
        self.appdata.mkdir(parents=True)
        self.zip = self.home / "Downloads" / pack.ZIP_NAME
        self.folder = Path(pack.pack_folder(str(self.appdata)))

    def tearDown(self):
        self.temp.cleanup()

    def test_imports_platforms_when_missing_and_answers_logos(self):
        fake_zip(self.zip)
        answer = pack.ensure_and_read(str(self.appdata), [str(self.home)])
        self.assertTrue(answer["ok"])
        self.assertTrue(answer["imported"])
        self.assertEqual(answer["slugs"], ["n64", "ps2", "psx"])
        for slug in ("psx", "ps2", "n64"):
            for name in pack.FILES:
                self.assertEqual((self.folder / "platforms" / slug / name).read_bytes(), (slug + ":" + name).encode())
        self.assertEqual(base64.b64decode(answer["logos"]["psx"].split(",", 1)[1]), b"psx:logo.png")
        # Present: not imported again.
        again = pack.ensure_and_read(str(self.appdata), [str(self.home)])
        self.assertNotIn("import", again)

    def test_reimport_replaces_the_folder_only_when_complete(self):
        fake_zip(self.zip)
        pack.ensure_and_read(str(self.appdata), [str(self.home)])
        self.zip.unlink()
        fake_zip(self.zip, slugs=("snes",))
        answer = pack.ensure_and_read(str(self.appdata), [str(self.home)], force=True)
        self.assertEqual(answer["slugs"], ["snes"])
        self.assertFalse((self.folder / "platforms.importing").exists())
        # A broken zip on re-import keeps what was there.
        self.zip.write_bytes(b"not a zip")
        broken = pack.ensure_and_read(str(self.appdata), [str(self.home)], force=True)
        self.assertEqual(broken["import"]["reason"], "bad_zip")
        self.assertEqual(broken["slugs"], ["snes"])

    def test_no_zip_is_reported_and_nothing_is_created_but_the_folder(self):
        answer = pack.ensure_and_read(str(self.appdata), [str(self.home)])
        self.assertEqual(answer["import"]["reason"], "zip_missing")
        self.assertEqual(answer["slugs"], [])
        self.assertFalse((self.folder / "platforms").exists())

    def test_only_plain_slugs_and_known_files_are_extracted(self):
        fake_zip(self.zip, slugs=("gba",), extra=[
            (PREFIX + "../evil/logo.png", b"x"), (PREFIX + "Bad Slug!/logo.png", b"x"), (PREFIX + "gba/readme.txt", b"x"),
            ("other/folder/logo.png", b"x"), (PREFIX + "gba/../../escape.png", b"x")])
        answer = pack.ensure_and_read(str(self.appdata), [str(self.home)])
        self.assertEqual(answer["slugs"], ["gba"])
        self.assertEqual(sorted(os.listdir(self.folder / "platforms" / "gba")), sorted(pack.FILES))
        self.assertFalse((self.folder / "evil").exists())
        self.assertFalse((self.root / "escape.png").exists())

    def test_families_logos_are_read_and_oversized_logos_are_skipped(self):
        family = self.folder / "families" / "sega"
        family.mkdir(parents=True)
        (family / "logo.png").write_bytes(b"sega")
        platforms = self.folder / "platforms" / "saturn"
        platforms.mkdir(parents=True)
        (platforms / "logo.png").write_bytes(b"x" * (pack.LOGO_MAX + 1))
        answer = pack.read_pack(str(self.folder))
        self.assertEqual(base64.b64decode(answer["families"]["sega"].split(",", 1)[1]), b"sega")
        self.assertEqual(answer["slugs"], ["saturn"])
        self.assertNotIn("saturn", answer["logos"])
        self.assertIn("logo_too_large:saturn", answer["errors"])

    def test_one_hero_per_call_only_for_a_plain_slug(self):
        # 3.3.10: the Consoles page asks for one hero at a time (generated bytes; never the real pack).
        hero = self.folder / "platforms" / "ps2"
        hero.mkdir(parents=True)
        (hero / "hero.png").write_bytes(b"ps2-hero")
        answer = pack.read_hero(str(self.folder), "ps2")
        self.assertTrue(answer["ok"])
        self.assertEqual(base64.b64decode(answer["url"].split(",", 1)[1]), b"ps2-hero")
        for bad in ("../ps2", "ps2/hero", "PS2", "", None, "a" * 60):
            self.assertFalse(pack.read_hero(str(self.folder), bad)["ok"], bad)
        self.assertEqual(pack.read_hero(str(self.folder), "n64")["error"], "missing")
        (hero / "hero.png").write_bytes(b"x" * (pack.HERO_MAX + 1))
        self.assertEqual(pack.read_hero(str(self.folder), "ps2")["error"], "too_large")
        self.assertFalse(pack.read_hero("", "ps2")["ok"])

    def test_the_pack_is_never_in_the_repository(self):
        plugin = Path(__file__).resolve().parents[1]
        for path in plugin.rglob("*"):
            if "node_modules" in path.parts:
                continue
            self.assertNotIn("colorgrade-icons-heroes-logos", path.name)
            self.assertNotEqual(path.parent.name, "by_platform")


if __name__ == "__main__":
    unittest.main()
